"""Generates lib/core/arabic/presentation_forms.dart.

Maps Arabic Presentation Forms-A (U+FB50-U+FDFF) and -B (U+FE70-U+FEFF)
code points to their compatibility decomposition (NFKC), so shaped glyph
codes extracted from PDFs become normal, searchable Arabic letters.

Usage: python3 tool/arabic/gen_presentation_forms.py
"""
import os
import unicodedata

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
OUT = os.path.join(ROOT, 'lib', 'core', 'arabic', 'presentation_forms.dart')

entries = []
for cp in list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFF00)):
    ch = chr(cp)
    if unicodedata.category(ch) == 'Cn':
        continue
    norm = unicodedata.normalize('NFKC', ch)
    if norm != ch:
        entries.append((cp, norm))

def dart_str(s):
    return "'" + ''.join('\\u{%X}' % ord(c) for c in s) + "'"

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by tool/arabic/gen_presentation_forms.py - do not edit.\n')
    f.write('// Unicode %s NFKC mappings for Arabic presentation forms.\n' % unicodedata.unidata_version)
    f.write('// ignore_for_file: lines_longer_than_80_chars\n\n')
    f.write('const Map<int, String> _kPresentationForms = {\n')
    for cp, norm in entries:
        f.write('  0x%04X: %s,\n' % (cp, dart_str(norm)))
    f.write('};\n\n')
    f.write('/// Replaces Arabic presentation-form code points with base letters.\n')
    f.write('String normalizePresentationForms(String input) {\n')
    f.write('  var hit = false;\n')
    f.write('  for (final r in input.runes) {\n')
    f.write('    if ((r >= 0xFB50 && r <= 0xFDFF) || (r >= 0xFE70 && r <= 0xFEFF)) {\n')
    f.write('      hit = true;\n')
    f.write('      break;\n')
    f.write('    }\n')
    f.write('  }\n')
    f.write('  if (!hit) return input;\n')
    f.write('  final b = StringBuffer();\n')
    f.write('  for (final r in input.runes) {\n')
    f.write('    final m = _kPresentationForms[r];\n')
    f.write('    if (m != null) {\n')
    f.write('      b.write(m);\n')
    f.write('    } else {\n')
    f.write('      b.writeCharCode(r);\n')
    f.write('    }\n')
    f.write('  }\n')
    f.write('  return b.toString();\n')
    f.write('}\n')
print('wrote', OUT, len(entries), 'entries')
