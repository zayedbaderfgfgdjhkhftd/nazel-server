// Generates lib/design/icon_data.g.dart from the Lucide icon set (ISC license).
//
// Usage: node tool/icons/gen_icons.js <path-to-lucide-static-package>
//   (get it with: npm pack lucide-static && tar xzf lucide-static-*.tgz)
//
// Icons are re-emitted with stroke-width 1.75 (design spec 7.4).
const fs = require('fs');
const path = require('path');

const pkg = process.argv[2];
if (!pkg) {
  console.error('usage: node tool/icons/gen_icons.js <lucide-static/package dir>');
  process.exit(1);
}

// Dart name -> lucide file name
