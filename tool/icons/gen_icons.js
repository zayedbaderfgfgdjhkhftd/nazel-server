  copy: 'copy',
  share: 'share-2',
  download: 'download',
  star: 'star',
  pencil: 'pencil',
  more: 'ellipsis-vertical',
  check: 'check',
  chevronStart: 'chevron-left',
  chevronEnd: 'chevron-right',
  arrowBack: 'arrow-left',
  eye: 'eye',
