  tools: 'layout-grid',
  folder: 'folder',
  settings: 'settings',
  fileText: 'file-text',
  merge: 'merge',
  split: 'split',
  extract: 'file-output',
  organize: 'layers',
  compress: 'shrink',
  pdfToImages: 'images',
  imagesToPdf: 'file-image',
  watermark: 'stamp',
  pageNumbers: 'list-ordered',
  signature: 'signature',
  textExtract: 'file-type',
  ocr: 'scan-text',
  info: 'info',
  search: 'search',
  close: 'x',
  plus: 'plus',
